//go:build ignore

// gen_metrics writes metrics_gen.go: advance widths, in thousandths of an em,
// of the Office fonts Word lays text out in, read from their metric-compatible
// OFL twins (Liberation, Carlito, Caladea; LibreOffice ships them).
//
//	go run gen_metrics.go /Applications/LibreOffice.app/Contents/Resources/fonts/truetype
package main

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
)

// The runes a face table covers, in order: Latin, punctuation, currency,
// letterlike symbols.
var ranges = [][2]rune{{0x20, 0x24f}, {0x2000, 0x206f}, {0x20a0, 0x20bf}, {0x2100, 0x2122}}

var faces = []struct{ family, file string }{
	{"Arial", "LiberationSans-Regular"}, {"Arial|b", "LiberationSans-Bold"}, {"Arial|i", "LiberationSans-Italic"}, {"Arial|bi", "LiberationSans-BoldItalic"},
	{"Times New Roman", "LiberationSerif-Regular"}, {"Times New Roman|b", "LiberationSerif-Bold"}, {"Times New Roman|i", "LiberationSerif-Italic"}, {"Times New Roman|bi", "LiberationSerif-BoldItalic"},
	{"Courier New", "LiberationMono-Regular"}, {"Courier New|b", "LiberationMono-Bold"}, {"Courier New|i", "LiberationMono-Italic"}, {"Courier New|bi", "LiberationMono-BoldItalic"},
	{"Calibri", "Carlito-Regular"}, {"Calibri|b", "Carlito-Bold"}, {"Calibri|i", "Carlito-Italic"}, {"Calibri|bi", "Carlito-BoldItalic"},
	{"Cambria", "Caladea-Regular"}, {"Cambria|b", "Caladea-Bold"}, {"Cambria|i", "Caladea-Italic"}, {"Cambria|bi", "Caladea-BoldItalic"},
}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: go run gen_metrics.go FONT_DIR")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_metrics.go; DO NOT EDIT.\n\npackage verso\n\n")
	fmt.Fprintf(&b, "var metricRanges = %#v\n\n", ranges)
	b.WriteString("var faceAdvances = map[string][]uint16{\n")
	for _, f := range faces {
		data, err := os.ReadFile(filepath.Join(os.Args[1], f.file+".ttf"))
		if err != nil {
			log.Fatal(err)
		}
		advances, err := advances(data)
		if err != nil {
			log.Fatalf("%s: %v", f.file, err)
		}
		fmt.Fprintf(&b, "%q: {", f.family)
		for _, r := range ranges {
			for c := r[0]; c <= r[1]; c++ {
				fmt.Fprintf(&b, "%d,", advances[c])
			}
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("metrics_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

// advances maps each rune the font's Unicode cmap covers to its advance in
// thousandths of an em.
func advances(data []byte) (map[rune]uint16, error) {
	tables := map[string][]byte{}
	n := int(binary.BigEndian.Uint16(data[4:]))
	for i := range n {
		rec := data[12+16*i:]
		off, length := binary.BigEndian.Uint32(rec[8:]), binary.BigEndian.Uint32(rec[12:])
		tables[string(rec[:4])] = data[off : off+length]
	}
	head, hhea, hmtx, cmap := tables["head"], tables["hhea"], tables["hmtx"], tables["cmap"]
	if head == nil || hhea == nil || hmtx == nil || cmap == nil {
		return nil, fmt.Errorf("missing a table")
	}
	upem := float64(binary.BigEndian.Uint16(head[18:]))
	metrics := int(binary.BigEndian.Uint16(hhea[34:]))
	advance := func(glyph int) uint16 {
		glyph = min(glyph, metrics-1)
		return uint16(float64(binary.BigEndian.Uint16(hmtx[4*glyph:]))*1000/upem + 0.5)
	}
	out := map[rune]uint16{}
	for i := range int(binary.BigEndian.Uint16(cmap[2:])) {
		rec := cmap[4+8*i:]
		platform, encoding := binary.BigEndian.Uint16(rec), binary.BigEndian.Uint16(rec[2:])
		sub := cmap[binary.BigEndian.Uint32(rec[4:]):]
		if platform != 3 || encoding != 1 || binary.BigEndian.Uint16(sub) != 4 {
			continue
		}
		segs := int(binary.BigEndian.Uint16(sub[6:])) / 2
		ends, starts := sub[14:], sub[16+2*segs:]
		deltas, offsets := sub[16+4*segs:], sub[16+6*segs:]
		for s := range segs {
			end, start := int(binary.BigEndian.Uint16(ends[2*s:])), int(binary.BigEndian.Uint16(starts[2*s:]))
			delta, ro := int(int16(binary.BigEndian.Uint16(deltas[2*s:]))), int(binary.BigEndian.Uint16(offsets[2*s:]))
			for c := start; c <= end && c != 0xffff; c++ {
				glyph := 0
				if ro == 0 {
					glyph = (c + delta) & 0xffff
				} else if at := 2*s + ro + 2*(c-start); at+1 < len(offsets) {
					if g := int(binary.BigEndian.Uint16(offsets[at:])); g != 0 {
						glyph = (g + delta) & 0xffff
					}
				}
				if glyph != 0 {
					out[rune(c)] = advance(glyph)
				}
			}
		}
		return out, nil
	}
	return nil, fmt.Errorf("no Windows Unicode BMP cmap")
}
